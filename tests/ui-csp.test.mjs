import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import test from 'node:test';
import { buildUiAssets } from '../scripts/build-ui-assets.mjs';

const html = await fs.readFile('index.html', 'utf8');
const config = JSON.parse(await fs.readFile('src-tauri/tauri.conf.json', 'utf8'));

test('desktop CSP keeps remote content blocked and whitelists only the exact bundled inline scripts', () => {
  const csp = config.app?.security?.csp;
  const scriptHashes = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)]
    .filter(([, script]) => script.trim())
    .map(([, script]) => `'sha256-${createHash('sha256').update(script).digest('base64')}'`);
  assert.ok(csp && typeof csp === 'object', 'production CSP must be enabled');
  assert.equal(csp['default-src'], "'self' customprotocol: asset:");
  assert.equal(csp['connect-src'], 'ipc: http://ipc.localhost http://127.0.0.1:*');
  assert.equal(csp['script-src'], `'self' ${scriptHashes.join(' ')}`);
  assert.equal(csp['object-src'], "'none'");
  assert.equal(csp['frame-src'], "'self' blob:", 'invoice PDF previews may frame local generated bytes only');
  assert.doesNotMatch(csp['script-src'], /unsafe-inline|unsafe-eval|https?:/);
  assert.doesNotMatch(html, /\son(?:click|input|submit)=/i, 'executable UI actions must use delegated listeners');
  assert.match(html, /officekitDispatchDelegatedEvent/);
  assert.deepEqual(csp['connect-src'].split(' '), ['ipc:', 'http://ipc.localhost', 'http://127.0.0.1:*']);
});

test('desktop HTML loads its fonts, styles and scripts from bundled assets only', () => {
  assert.doesNotMatch(html, /<script\s+src=["']https?:/i);
  assert.doesNotMatch(html, /<link\s+[^>]*href=["']https?:/i);
  assert.match(html, /assets\/officekit\.css/);
  assert.match(html, /assets\/fontawesome\/css\/fontawesome\.min\.css/);
  assert.match(html, /assets\/fontawesome\/css\/solid\.min\.css/);
  assert.doesNotMatch(html, /tailwind\.config|tailwindcss\.com/i);
});

test('desktop HTML contains only local inline scripts with exact hashes in the production CSP', () => {
  const inlineScripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(([, script]) => script.trim());
  assert.equal(inlineScripts.length, 3, 'the prepaint appearance preference adds one hashed inline script');
  for (const [, script] of inlineScripts) {
    const hash = `'sha256-${createHash('sha256').update(script).digest('base64')}'`;
    assert.ok(config.app.security.csp['script-src'].includes(hash), `the production CSP must allow script ${hash}`);
  }
});

test('UI asset build bundles icon/font files and their licenses beside generated CSS', async () => {
  const { output, cssBytes } = await buildUiAssets();
  assert.ok(cssBytes > 1_000, 'Tailwind should produce the app utility styles');
  for (const relativePath of [
    'officekit.css',
    'fontawesome/css/fontawesome.min.css',
    'fontawesome/css/solid.min.css',
    'fontawesome/webfonts/fa-solid-900.woff2',
    'fonts/plus-jakarta-sans-latin-wght-normal.woff2',
    'fonts/jetbrains-mono-latin-wght-normal.woff2',
    'licenses/fontawesome.txt',
    'licenses/tailwindcss.txt',
    'licenses/plus-jakarta-sans.txt',
    'licenses/jetbrains-mono.txt',
  ]) {
    const asset = await fs.stat(`${output}/${relativePath}`);
    assert.ok(asset.isFile(), `${relativePath} must be packaged`);
    assert.ok(asset.size > 0, `${relativePath} must not be empty`);
  }
  const css = await fs.readFile(`${output}/officekit.css`, 'utf8');
  assert.match(css, /font-family:["']?Plus Jakarta Sans/i);
  assert.match(css, /font-family:["']?JetBrains Mono/i);
});
