"""
Unit tests for the Unified Clipboard Manager & Snippets Studio Engine.
Covers:
- Adding, deduplicating, bumping, and pruning clips in SQLite
- Privacy gate filtering (1Password, Bitwarden, KeePass, ConcealedType)
- Pinning and selective history deletion
- CopyQ string transformations (casing, trimming, slugify, JSON formatting, URL/email extraction)
- Clipy snippet folders, hierarchy, and JSON import/export
- Espanso dynamic template parsing and variable substitution
"""

import os
import tempfile
import pytest

from officekit.engines.engine_clipboard import (
    ClipboardStore,
    is_concealed_metadata,
    detect_content_type,
    apply_transformation,
    parse_template_variables,
    render_template,
)


@pytest.fixture
def temp_store():
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
        db_path = f.name
    store = ClipboardStore(db_path=db_path, max_clips=5)
    yield store
    if os.path.exists(db_path):
        os.remove(db_path)


def test_privacy_filter():
    assert is_concealed_metadata(["org.nspasteboard.ConcealedType"]) is True
    assert is_concealed_metadata(["com.agilebits.onepassword"]) is True
    assert is_concealed_metadata(["org.nspasteboard.AutoGeneratedType"]) is True
    assert is_concealed_metadata(["public.utf8-plain-text"]) is False
    assert is_concealed_metadata(None) is False
    assert is_concealed_metadata([]) is False


def test_content_type_detection():
    assert detect_content_type("https://officekit.app") == "link"
    assert detect_content_type('{"key": "value"}') == "json"
    assert detect_content_type("[1, 2, 3]") == "json"
    assert detect_content_type("function calculateTotal() {\n  return 42;\n}") == "code"
    assert detect_content_type("Hello world this is normal text") == "text"
    assert detect_content_type("Any text", has_image=True) == "image"


def test_add_and_list_clips(temp_store):
    # Concealed clip should be ignored
    res = temp_store.add_clip(
        "secret-password",
        metadata_types=["org.nspasteboard.ConcealedType"]
    )
    assert res is None
    assert temp_store.list_clips()["total"] == 0

    # Normal clip
    clip1 = temp_store.add_clip("https://example.com/docs")
    assert clip1 is not None
    assert clip1["category"] == "link"
    assert clip1["text_content"] == "https://example.com/docs"

    # Repeated clip should bump, not duplicate
    clip1_again = temp_store.add_clip("https://example.com/docs")
    assert clip1_again["id"] == clip1["id"]
    assert temp_store.list_clips()["total"] == 1


def test_pinning_and_pruning(temp_store):
    # Add 5 clips
    for i in range(5):
        temp_store.add_clip(f"clip {i}")

    assert temp_store.list_clips()["total"] == 5

    # Pin clip 0
    clips = temp_store.list_clips()["clips"]
    earliest_clip = [c for c in clips if c["text_content"] == "clip 0"][0]
    pinned = temp_store.toggle_pin(earliest_clip["id"])
    assert pinned["pinned"] == 1

    # Add 2 more clips (max is 5, so 2 unpinned should be pruned)
    temp_store.add_clip("clip 5")
    temp_store.add_clip("clip 6")

    all_clips = temp_store.list_clips()["clips"]
    assert len(all_clips) <= 5
    # Pinned item MUST still exist
    assert any(c["id"] == earliest_clip["id"] for c in all_clips)


def test_clear_history(temp_store):
    c1 = temp_store.add_clip("keep me")
    c2 = temp_store.add_clip("delete me")
    temp_store.toggle_pin(c1["id"], True)

    # Keep pinned
    deleted = temp_store.clear_history(keep_pinned=True)
    assert deleted >= 1
    remaining = temp_store.list_clips()["clips"]
    assert len(remaining) == 1
    assert remaining[0]["id"] == c1["id"]

    # Delete all including pinned
    temp_store.clear_history(keep_pinned=False)
    assert temp_store.list_clips()["total"] == 0


def test_transformations():
    # Trim
    assert apply_transformation("  hello world  ", "trim")["result"] == "hello world"
    # Casing
    assert apply_transformation("hello world", "uppercase")["result"] == "HELLO WORLD"
    assert apply_transformation("HELLO WORLD", "lowercase")["result"] == "hello world"
    assert apply_transformation("hello world", "titlecase")["result"] == "Hello World"
    # Slugify
    assert apply_transformation("My First Blog Post!", "slugify")["result"] == "my-first-blog-post"
    # Strip HTML
    assert apply_transformation("<h1>Title</h1><p>Body &amp; content</p>", "strip_html")["result"] == "TitleBody & content"
    # JSON Prettify & Minify
    json_raw = '{"name":"OfficeKit","active":true}'
    prettified = apply_transformation(json_raw, "prettify_json")["result"]
    assert "  \"name\": \"OfficeKit\"" in prettified
    minified = apply_transformation(prettified, "minify_json")["result"]
    assert minified == json_raw
    # Extract URLs & Emails
    text_with_data = "Contact user@example.com or visit https://officekit.app for details. Also support@officekit.app"
    urls = apply_transformation(text_with_data, "extract_urls")["result"]
    assert urls == "https://officekit.app"
    emails = apply_transformation(text_with_data, "extract_emails")["result"]
    assert "user@example.com" in emails
    assert "support@officekit.app" in emails


def test_snippets_crud_and_import_export(temp_store):
    # Create folder
    folder = temp_store.create_folder("Customer Support", icon="fa-headset")
    assert folder["name"] == "Customer Support"
    assert len(temp_store.list_folders()) == 2  # default + new

    # Create snippet
    snip = temp_store.save_snippet(
        title="Intro Greeting",
        content="Hello {{name}}, thanks for reaching out!",
        folder_id=folder["id"],
        trigger_key=":hi",
        shortcut_number=1,
    )
    assert snip["title"] == "Intro Greeting"
    assert snip["folder_name"] == "Customer Support"
    assert snip["trigger_key"] == ":hi"

    # Export
    exported = temp_store.export_snippets()
    assert "folders" in exported
    assert "snippets" in exported
    assert len(exported["snippets"]) == 1

    # Import into fresh store
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
        fresh_db = f.name
    fresh_store = ClipboardStore(db_path=fresh_db)
    res = fresh_store.import_snippets(exported)
    assert res["imported_snippets"] == 1
    assert len(fresh_store.list_snippets()) == 1

    # Clean up
    if os.path.exists(fresh_db):
        os.remove(fresh_db)


def test_template_variables_and_rendering():
    template = "Invoice for {{client}} on {{date}} with ID {{uuid}}. Prev: {{clipboard}}"
    vars_found = parse_template_variables(template)
    names = [v["name"] for v in vars_found]
    assert "client" in names
    assert "date" in names
    assert "uuid" in names
    assert "clipboard" in names

    rendered = render_template(
        template,
        values={"client": "Acme Corp"},
        current_clipboard="Item #1234"
    )
    assert "Invoice for Acme Corp" in rendered
    assert "Prev: Item #1234" in rendered
    assert "{{date}}" not in rendered
    assert "{{uuid}}" not in rendered


def test_api_clipboard_endpoints():
    from fastapi.testclient import TestClient
    from app import app

    client = TestClient(app)

    # 1. Save clip via API
    resp = client.post("/api/clipboard/clips", json={
        "text_content": "API Clip Test 1",
        "category": "general",
        "source_app": "Terminal"
    })
    assert resp.status_code == 200
    clip = resp.json()["clip"]
    assert clip["text_content"] == "API Clip Test 1"
    clip_id = clip["id"]

    # 2. Get history
    resp = client.get("/api/clipboard/history")
    assert resp.status_code == 200
    data = resp.json()
    assert any(c["id"] == clip_id for c in data["clips"])

    # 3. Pin clip
    resp = client.post(f"/api/clipboard/clips/{clip_id}/pin", json={"pinned": True})
    assert resp.status_code == 200
    assert resp.json()["clip"]["pinned"] == 1

    # 3b. Using a clip marks it as just used; an unknown clip is a 404
    resp = client.post(f"/api/clipboard/clips/{clip_id}/use")
    assert resp.status_code == 200
    assert resp.json()["clip"]["id"] == clip_id
    assert client.post("/api/clipboard/clips/does-not-exist/use").status_code == 404

    # 4. Transform text
    resp = client.post("/api/clipboard/transform", json={"text": "hello world", "transform": "uppercase"})
    assert resp.status_code == 200
    assert resp.json()["result"] == "HELLO WORLD"

    # 5. Folders & Snippets
    resp = client.get("/api/clipboard/folders")
    assert resp.status_code == 200
    assert len(resp.json()["folders"]) >= 1

    resp = client.post("/api/clipboard/folders", json={"name": "Dev Snippets", "icon": "fa-code"})
    assert resp.status_code == 200
    folder_id = resp.json()["folder"]["id"]

    resp = client.post("/api/clipboard/snippets", json={
        "title": "SQL Query",
        "content": "SELECT * FROM users WHERE active = 1;",
        "folder_id": folder_id,
        "trigger_key": ":users"
    })
    assert resp.status_code == 200
    snip_id = resp.json()["snippet"]["id"]

    # 6. Render template
    resp = client.post("/api/clipboard/snippets/render", json={
        "template": "Hello {{name}}, today is {{date}}",
        "values": {"name": "Alice"}
    })
    assert resp.status_code == 200
    assert "Hello Alice, today is" in resp.json()["rendered"]

    # 7. Delete snippet and folder
    resp = client.delete(f"/api/clipboard/snippets/{snip_id}")
    assert resp.status_code == 200

    resp = client.delete(f"/api/clipboard/folders/{folder_id}")
    assert resp.status_code == 200

    # 8. Delete clip
    resp = client.delete(f"/api/clipboard/clips/{clip_id}")
    assert resp.status_code == 200

