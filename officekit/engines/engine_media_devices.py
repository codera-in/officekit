def resolve_device_aspect(name):
    """Resolve a Clop-compatible device name without accepting fuzzy matches."""
    if not isinstance(name, str) or not name.strip():
        raise ValueError("Choose a supported device name")
    normalized = name.strip().casefold()
    for device, aspect in DEVICE_ASPECTS.items():
        if device.casefold() == normalized:
            width, height = (int(part) for part in aspect.split(":"))
            return f"{min(width, height)}:{max(width, height)}"
    raise ValueError(f'Unknown device "{name.strip()}"; use --list-devices to see supported values')


def supported_devices():
    return tuple(sorted(DEVICE_ASPECTS, key=str.casefold))


def resolve_paper_aspect(name):
    if not isinstance(name, str) or not name.strip():
        raise ValueError("Choose a supported paper size")
    normalized = name.strip().casefold()
    for paper_size, aspect in PAPER_SIZE_ASPECTS.items():
        if paper_size.casefold() == normalized:
            width, height = (int(part) for part in aspect.split(":"))
            return f"{min(width, height)}:{max(width, height)}"
    raise ValueError(f'Unknown paper size "{name.strip()}"; use --list-paper-sizes to see supported values')


def supported_paper_sizes():
    return tuple(sorted(PAPER_SIZE_ASPECTS, key=str.casefold))

