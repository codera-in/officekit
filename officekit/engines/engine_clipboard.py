"""
OfficeKit - Unified Clipboard Manager & Snippets Studio Engine.
Synthesizes the best capabilities of PasteBar, Maccy, Clipy, CopyQ, and Espanso:
- Unlimited/configurable local-first SQLite clipboard history with auto-pruning
- Privacy-first concealment checking for password managers (1Password, Bitwarden, Keychain)
- CopyQ-inspired multi-format transformations (casing, trimming, slugify, JSON formatting, sanitization)
- Clipy-inspired hierarchical snippet folders with JSON/YAML import/export
- Espanso-inspired dynamic template evaluation (built-ins and interactive prompt variables)
"""

from __future__ import annotations

import datetime
import html
import json
import os
import re
import sqlite3
import sys
import time
import uuid
from typing import Any, Dict, List, Optional, Tuple


CONCEALED_METADATA_TYPES = frozenset([
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "org.nspasteboard.TransientType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
])

DEFAULT_MAX_CLIPS = 500
DEFAULT_RETENTION_DAYS = 30
MAX_TEXT_SIZE_BYTES = 5 * 1024 * 1024  # 5 MB per clip
MAX_IMAGE_PREVIEW_BYTES = 2 * 1024 * 1024  # 2 MB thumbnail/data

# Capture pause choices. "off" means capture runs; "until_resume" has no end time.
TIMED_PAUSE_SECONDS = {"15m": 15 * 60, "1h": 60 * 60}
CAPTURE_PAUSE_CHOICES = ("off", "15m", "1h", "until_resume")
# The filter the clipboard panel opens on; "text" includes links.
PANEL_FILTER_CHOICES = ("all", "text", "images", "links", "pinned")
DEFAULT_PANEL_FILTER = "text"


def _timed_pause_active(settings: Dict[str, Any], now: float) -> bool:
    until = settings.get("capture_paused_until")
    return (
        settings.get("capture_pause") in TIMED_PAUSE_SECONDS
        and isinstance(until, (int, float))
        and not isinstance(until, bool)
        and until > now
    )


def is_capture_paused(settings: Dict[str, Any], now: float) -> bool:
    """True while a pause is in force: indefinitely for until_resume, else until its end time."""
    return settings.get("capture_pause") == "until_resume" or _timed_pause_active(settings, now)

# Sources whose copies are never stored unless the user edits the list.
DEFAULT_SKIP_BUNDLE_IDS = (
    "com.1password.1password",
    "com.agilebits.onepassword7",
    "com.bitwarden.desktop",
    "com.apple.keychainaccess",
    "com.apple.Passwords",
    "org.keepassxc.keepassxc",
)
BUNDLE_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,254}$")

# History filter chips mapped to stored content types.
CLIP_TYPE_FILTERS = {
    "text": ("text", "code", "json"),
    "link": ("link",),
    "image": ("image",),
}

TRIGGER_MIN_LENGTH = 2
TRIGGER_MAX_LENGTH = 32


class TriggerError(ValueError):
    """A snippet keyword that cannot expand unambiguously. `code` names the rule that failed."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def validate_trigger_shape(trigger: str) -> None:
    if not TRIGGER_MIN_LENGTH <= len(trigger) <= TRIGGER_MAX_LENGTH:
        raise TriggerError("length", f"A snippet keyword needs {TRIGGER_MIN_LENGTH} to {TRIGGER_MAX_LENGTH} characters")
    if any(ch.isspace() or ord(ch) < 32 for ch in trigger):
        raise TriggerError("whitespace", "A snippet keyword cannot contain spaces or control characters")


def is_concealed_metadata(metadata_types: Optional[List[str]]) -> bool:
    """Return True if any clipboard metadata type marks the content as concealed/transient."""
    if not metadata_types:
        return False
    for item in metadata_types:
        if isinstance(item, str) and item.strip() in CONCEALED_METADATA_TYPES:
            return True
    return False


def detect_content_type(text: str, has_image: bool = False) -> str:
    """Classify clip content as text, code, link, json, or image."""
    if has_image:
        return "image"
    if not text:
        return "text"
    stripped = text.strip()
    if re.match(r"^https?://[^\s/$.?#].[^\s]*$", stripped, re.IGNORECASE):
        return "link"
    if (stripped.startswith("{") and stripped.endswith("}")) or (stripped.startswith("[") and stripped.endswith("]")):
        try:
            json.loads(stripped)
            return "json"
        except Exception:
            pass
    code_indicators = [
        "function ", "const ", "let ", "var ", "def ", "class ", "import ",
        "export ", "SELECT ", "INSERT INTO ", "UPDATE ", "DELETE FROM ",
        "<html>", "<div", "<script", "curl ", "docker ", "git commit", "public static void"
    ]
    if "\n" in stripped and any(indicator in stripped for indicator in code_indicators):
        return "code"
    return "text"


def _storage_directory() -> str:
    override = os.environ.get("OFFICEKIT_DATA_DIR")
    if override:
        return override
    if sys.platform == "darwin":
        data_root = os.path.join(os.path.expanduser("~"), "Library", "Application Support")
    elif os.name == "nt":
        data_root = os.environ.get("APPDATA") or os.path.join(os.path.expanduser("~"), "AppData", "Roaming")
    else:
        data_root = os.environ.get("XDG_STATE_HOME") or os.path.join(os.path.expanduser("~"), ".local", "state")
    return os.path.join(data_root, "OfficeKit")


class ClipboardStore:
    """Thread-safe SQLite persistent store for clipboard history and snippet library."""

    def __init__(self, db_path: Optional[str] = None, max_clips: int = DEFAULT_MAX_CLIPS):
        self.max_clips = max_clips
        if db_path is None:
            env_path = os.environ.get("OFFICEKIT_CLIPBOARD_DB_PATH")
            if env_path:
                self.db_path = env_path
            else:
                base_dir = _storage_directory()
                os.makedirs(base_dir, exist_ok=True)
                self.db_path = os.path.join(base_dir, "clipboard.db")
        else:
            self.db_path = db_path
            if self.db_path != ":memory:":
                parent = os.path.dirname(os.path.abspath(self.db_path))
                if parent:
                    os.makedirs(parent, exist_ok=True)
        self._init_db()
        if self.db_path != ":memory:":
            # Retention also applies on start, so lowering it or pausing capture still removes old clips.
            with self._get_connection() as conn:
                self._prune(conn.cursor(), time.time())
                conn.commit()
            try:
                os.chmod(self.db_path, 0o600)
            except OSError:
                pass

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON;")
        # Deleted clips must not linger in free pages.
        conn.execute("PRAGMA secure_delete = ON;")
        return conn

    def _init_db(self) -> None:
        with self._get_connection() as conn:
            conn.executescript("""
                CREATE TABLE IF NOT EXISTS clips (
                    id TEXT PRIMARY KEY,
                    content_type TEXT NOT NULL,
                    text_content TEXT NOT NULL,
                    rich_content TEXT,
                    image_data TEXT,
                    category TEXT NOT NULL DEFAULT 'general',
                    pinned INTEGER NOT NULL DEFAULT 0,
                    created_at REAL NOT NULL,
                    last_used_at REAL NOT NULL,
                    char_count INTEGER NOT NULL DEFAULT 0,
                    word_count INTEGER NOT NULL DEFAULT 0,
                    byte_size INTEGER NOT NULL DEFAULT 0,
                    source_app TEXT
                );
                CREATE INDEX IF NOT EXISTS idx_clips_created_at ON clips(created_at DESC);
                CREATE INDEX IF NOT EXISTS idx_clips_pinned ON clips(pinned DESC);
                CREATE INDEX IF NOT EXISTS idx_clips_category ON clips(category);

                CREATE TABLE IF NOT EXISTS snippet_folders (
                    id TEXT PRIMARY KEY,
                    name TEXT NOT NULL,
                    icon TEXT NOT NULL DEFAULT 'fa-folder',
                    created_at REAL NOT NULL
                );

                CREATE TABLE IF NOT EXISTS snippets (
                    id TEXT PRIMARY KEY,
                    title TEXT NOT NULL,
                    folder_id TEXT NOT NULL DEFAULT 'default',
                    content TEXT NOT NULL,
                    trigger_key TEXT,
                    shortcut_number INTEGER,
                    created_at REAL NOT NULL,
                    updated_at REAL NOT NULL,
                    FOREIGN KEY (folder_id) REFERENCES snippet_folders(id) ON DELETE SET DEFAULT
                );
                CREATE INDEX IF NOT EXISTS idx_snippets_folder ON snippets(folder_id);
                CREATE INDEX IF NOT EXISTS idx_snippets_trigger ON snippets(trigger_key);
            """)
            # Additive migrations for databases created before the global desktop layer.
            columns = {row["name"] for row in conn.execute("PRAGMA table_info(clips)")}
            if "source_bundle_id" not in columns:
                conn.execute("ALTER TABLE clips ADD COLUMN source_bundle_id TEXT")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_clips_pinned_used ON clips(pinned DESC, last_used_at DESC)")
            conn.execute("CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
            # Ensure default folder exists
            cursor = conn.cursor()
            cursor.execute("SELECT id FROM snippet_folders WHERE id = 'default'")
            if not cursor.fetchone():
                cursor.execute(
                    "INSERT INTO snippet_folders (id, name, icon, created_at) VALUES ('default', 'General', 'fa-folder', ?)",
                    (time.time(),)
                )
            conn.commit()

    # --------------------------------------------------------------------------
    # Clips Management (History, Pinning, Pruning)
    # --------------------------------------------------------------------------

    def add_clip(
        self,
        text_content: str,
        content_type: Optional[str] = None,
        rich_content: Optional[str] = None,
        image_data: Optional[str] = None,
        category: Optional[str] = None,
        source_app: Optional[str] = None,
        metadata_types: Optional[List[str]] = None,
        source_bundle_id: Optional[str] = None,
    ) -> Optional[Dict[str, Any]]:
        """Add a new clip to history after privacy filtering, deduplication, and auto-pruning."""
        if is_concealed_metadata(metadata_types):
            return None
        # Bundle identifiers are case-insensitive, so the skip list matches the same way.
        if source_bundle_id and source_bundle_id.casefold() in {
            skipped.casefold() for skipped in self.get_settings()["skip_bundle_ids"]
        }:
            return None

        text = text_content or ""
        if len(text.encode("utf-8")) > MAX_TEXT_SIZE_BYTES:
            text = text[:MAX_TEXT_SIZE_BYTES]

        if not text and not image_data:
            return None

        now = time.time()
        c_type = content_type or detect_content_type(text, bool(image_data))
        cat = category or ("code" if c_type in ("code", "json") else ("link" if c_type == "link" else ("image" if c_type == "image" else "general")))
        char_c = len(text)
        word_c = len(text.split()) if text else 0
        byte_sz = len(text.encode("utf-8")) + (len(image_data.encode("utf-8")) if image_data else 0)

        with self._get_connection() as conn:
            cursor = conn.cursor()
            # An identical text clip anywhere in history moves to the top instead of duplicating.
            if not image_data:
                cursor.execute(
                    "SELECT id FROM clips WHERE text_content = ? AND image_data IS NULL LIMIT 1", (text,)
                )
                existing = cursor.fetchone()
                if existing:
                    cursor.execute(
                        """
                        UPDATE clips SET created_at = ?, last_used_at = ?,
                            source_app = coalesce(?, source_app),
                            source_bundle_id = coalesce(?, source_bundle_id)
                        WHERE id = ?
                        """,
                        (now, now, source_app, source_bundle_id, existing["id"])
                    )
                    conn.commit()
                    return self.get_clip(existing["id"])

            clip_id = str(uuid.uuid4())
            cursor.execute(
                """
                INSERT INTO clips (
                    id, content_type, text_content, rich_content, image_data,
                    category, pinned, created_at, last_used_at, char_count,
                    word_count, byte_size, source_app, source_bundle_id
                ) VALUES (?, ?, ?, ?, ?, ?, 0, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    clip_id, c_type, text, rich_content, image_data,
                    cat, now, now, char_c, word_c, byte_sz, source_app, source_bundle_id
                )
            )

            self._prune(cursor, now)
            conn.commit()

        return self.get_clip(clip_id)

    def _prune(self, cursor: sqlite3.Cursor, now: float) -> None:
        """Delete unpinned clips beyond the retention count and age."""
        settings = self._read_settings(cursor)
        cursor.execute(
            """
            DELETE FROM clips
            WHERE pinned = 0 AND id NOT IN (
                SELECT id FROM clips ORDER BY pinned DESC, created_at DESC LIMIT ?
            )
            """,
            (settings["retention_clips"],)
        )
        cursor.execute(
            "DELETE FROM clips WHERE pinned = 0 AND created_at < ?",
            (now - settings["retention_days"] * 86400,)
        )

    # --------------------------------------------------------------------------
    # Global capture settings (shared by the native clipboard watcher and the settings card)
    # --------------------------------------------------------------------------

    def _settings_defaults(self) -> Dict[str, Any]:
        return {
            "capture_enabled": True,
            "expansion_enabled": True,
            "skip_bundle_ids": list(DEFAULT_SKIP_BUNDLE_IDS),
            "retention_clips": self.max_clips,
            "retention_days": DEFAULT_RETENTION_DAYS,
            # "off" resumes capture; "15m" and "1h" end by themselves at capture_paused_until;
            # "until_resume" stays paused until the user resumes. Pausing never deletes history.
            "capture_pause": "off",
            "capture_paused_until": None,
            "panel_default_filter": DEFAULT_PANEL_FILTER,
        }

    def _read_settings(self, cursor: sqlite3.Cursor) -> Dict[str, Any]:
        settings = self._settings_defaults()
        cursor.execute("SELECT key, value FROM settings")
        for row in cursor.fetchall():
            if row["key"] in settings:
                try:
                    settings[row["key"]] = json.loads(row["value"])
                except ValueError:
                    continue
        # A timed pause that has run out reads as resumed, so the stored value never goes stale.
        if not _timed_pause_active(settings, time.time()) and settings["capture_pause"] in TIMED_PAUSE_SECONDS:
            settings["capture_pause"] = "off"
            settings["capture_paused_until"] = None
        settings["capture_paused"] = is_capture_paused(settings, time.time())
        return settings

    def get_settings(self) -> Dict[str, Any]:
        with self._get_connection() as conn:
            return self._read_settings(conn.cursor())

    def update_settings(self, values: Dict[str, Any]) -> Dict[str, Any]:
        """Validate and persist the supplied settings keys; unknown keys and bad values raise ValueError."""
        # The pause end time is derived here from the pause choice, never taken from a client.
        allowed = {key for key in self._settings_defaults() if key != "capture_paused_until"}
        for key, value in values.items():
            if key not in allowed:
                raise ValueError(f"Unknown setting: {key}")
            if key == "capture_pause":
                if value not in CAPTURE_PAUSE_CHOICES:
                    raise ValueError("capture_pause must be off, 15m, 1h or until_resume")
            elif key == "panel_default_filter":
                if value not in PANEL_FILTER_CHOICES:
                    raise ValueError("panel_default_filter must be all, text, images, links or pinned")
            elif key in ("capture_enabled", "expansion_enabled"):
                if not isinstance(value, bool):
                    raise ValueError(f"{key} must be true or false")
            elif key == "retention_clips":
                if isinstance(value, bool) or not isinstance(value, int) or not 50 <= value <= 5000:
                    raise ValueError("retention_clips must be between 50 and 5000")
            elif key == "retention_days":
                if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= 365:
                    raise ValueError("retention_days must be between 1 and 365")
            elif key == "skip_bundle_ids":
                if (
                    not isinstance(value, list)
                    or len(value) > 64
                    or any(not isinstance(item, str) or not BUNDLE_ID_PATTERN.match(item) for item in value)
                ):
                    raise ValueError("skip_bundle_ids must be up to 64 bundle identifiers")
        now = time.time()
        stored = dict(values)
        if "capture_pause" in stored:
            pause = stored["capture_pause"]
            stored["capture_paused_until"] = now + TIMED_PAUSE_SECONDS[pause] if pause in TIMED_PAUSE_SECONDS else None
        with self._get_connection() as conn:
            for key, value in stored.items():
                conn.execute(
                    "INSERT INTO settings (key, value) VALUES (?, ?) "
                    "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                    (key, json.dumps(value)),
                )
            # Tighter retention applies immediately, not at the next copy.
            self._prune(conn.cursor(), time.time())
            conn.commit()
            return self._read_settings(conn.cursor())

    def get_clip(self, clip_id: str) -> Optional[Dict[str, Any]]:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM clips WHERE id = ?", (clip_id,))
            row = cursor.fetchone()
            return dict(row) if row else None

    def list_clips(
        self,
        search: Optional[str] = None,
        category: Optional[str] = None,
        pinned_only: bool = False,
        limit: int = 50,
        offset: int = 0,
        types: Optional[List[str]] = None,
        include_image_data: bool = True,
    ) -> Dict[str, Any]:
        """Fetch clips with optional search, category filter, type filter, and pagination.

        With `include_image_data` false the image bytes are left out and `has_image` marks image clips,
        so list views never move megabytes they only show a label for.
        """
        columns = "*" if include_image_data else (
            "id, content_type, text_content, rich_content, NULL AS image_data, "
            "(image_data IS NOT NULL) AS has_image, category, pinned, created_at, last_used_at, "
            "char_count, word_count, byte_size, source_app, source_bundle_id"
        )
        query = f"SELECT {columns} FROM clips WHERE 1=1"
        count_query = "SELECT COUNT(*) as total FROM clips WHERE 1=1"
        params: List[Any] = []

        if types:
            content_types = sorted({ct for name in types for ct in CLIP_TYPE_FILTERS.get(name, ())})
            if not content_types:
                content_types = ["__none__"]
            marks = ",".join("?" for _ in content_types)
            query += f" AND content_type IN ({marks})"
            count_query += f" AND content_type IN ({marks})"
            params.extend(content_types)

        if pinned_only:
            query += " AND pinned = 1"
            count_query += " AND pinned = 1"

        if category and category != "all":
            query += " AND category = ?"
            count_query += " AND category = ?"
            params.append(category)

        if search and search.strip():
            query += " AND (text_content LIKE ? OR source_app LIKE ?)"
            count_query += " AND (text_content LIKE ? OR source_app LIKE ?)"
            like_term = f"%{search.strip()}%"
            params.extend([like_term, like_term])

        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(count_query, params)
            total = cursor.fetchone()["total"]

            # Also get pinned count
            cursor.execute("SELECT COUNT(*) as pinned_count FROM clips WHERE pinned = 1")
            pinned_count = cursor.fetchone()["pinned_count"]

            query += " ORDER BY pinned DESC, created_at DESC LIMIT ? OFFSET ?"
            paged_params = list(params) + [max(1, min(limit, 200)), max(0, offset)]
            cursor.execute(query, paged_params)
            rows = [dict(row) for row in cursor.fetchall()]

        return {
            "clips": rows,
            "total": total,
            "pinned_count": pinned_count,
            "limit": limit,
            "offset": offset,
        }

    def toggle_pin(self, clip_id: str, pinned: Optional[bool] = None) -> Optional[Dict[str, Any]]:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT pinned FROM clips WHERE id = ?", (clip_id,))
            row = cursor.fetchone()
            if not row:
                return None
            new_status = (1 if pinned else 0) if pinned is not None else (0 if row["pinned"] else 1)
            cursor.execute("UPDATE clips SET pinned = ? WHERE id = ?", (new_status, clip_id))
            conn.commit()
        return self.get_clip(clip_id)

    def touch_clip(self, clip_id: str) -> Optional[Dict[str, Any]]:
        """Mark a clip as just used so it moves to the top of its group (pinned clips stay pinned)."""
        now = time.time()
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(
                "UPDATE clips SET created_at = ?, last_used_at = ? WHERE id = ?", (now, now, clip_id)
            )
            conn.commit()
            if cursor.rowcount == 0:
                return None
        return self.get_clip(clip_id)

    def delete_clip(self, clip_id: str) -> bool:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("DELETE FROM clips WHERE id = ?", (clip_id,))
            conn.commit()
            return cursor.rowcount > 0

    def clear_history(self, keep_pinned: bool = True) -> int:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            if keep_pinned:
                cursor.execute("DELETE FROM clips WHERE pinned = 0")
            else:
                cursor.execute("DELETE FROM clips")
            conn.commit()
            return cursor.rowcount

    # --------------------------------------------------------------------------
    # Snippets & Folder Management (Clipy & Espanso)
    # --------------------------------------------------------------------------

    def list_folders(self) -> List[Dict[str, Any]]:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT * FROM snippet_folders ORDER BY name ASC")
            return [dict(row) for row in cursor.fetchall()]

    def create_folder(self, name: str, icon: str = "fa-folder") -> Dict[str, Any]:
        folder_id = str(uuid.uuid4())
        now = time.time()
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(
                "INSERT INTO snippet_folders (id, name, icon, created_at) VALUES (?, ?, ?, ?)",
                (folder_id, name.strip() or "Untitled", icon, now)
            )
            conn.commit()
        return {"id": folder_id, "name": name.strip() or "Untitled", "icon": icon, "created_at": now}

    def delete_folder(self, folder_id: str) -> bool:
        if folder_id == "default":
            return False
        with self._get_connection() as conn:
            cursor = conn.cursor()
            # Move snippets in this folder to 'default'
            cursor.execute("UPDATE snippets SET folder_id = 'default' WHERE folder_id = ?", (folder_id,))
            cursor.execute("DELETE FROM snippet_folders WHERE id = ?", (folder_id,))
            conn.commit()
            return cursor.rowcount > 0

    def list_snippets(self, folder_id: Optional[str] = None, search: Optional[str] = None) -> List[Dict[str, Any]]:
        query = "SELECT s.*, f.name as folder_name FROM snippets s LEFT JOIN snippet_folders f ON s.folder_id = f.id WHERE 1=1"
        params: List[Any] = []
        if folder_id:
            query += " AND s.folder_id = ?"
            params.append(folder_id)
        if search and search.strip():
            query += " AND (s.title LIKE ? OR s.content LIKE ? OR s.trigger_key LIKE ?)"
            term = f"%{search.strip()}%"
            params.extend([term, term, term])
        query += " ORDER BY s.shortcut_number ASC NULLS LAST, s.title ASC"

        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute(query, params)
            return [dict(row) for row in cursor.fetchall()]

    def save_snippet(
        self,
        title: str,
        content: str,
        folder_id: str = "default",
        trigger_key: Optional[str] = None,
        shortcut_number: Optional[int] = None,
        snippet_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        now = time.time()
        sid = snippet_id or str(uuid.uuid4())
        shortcut = shortcut_number if (shortcut_number is not None and 1 <= shortcut_number <= 9) else None
        clean_trigger = trigger_key.strip() if trigger_key and trigger_key.strip() else None

        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT id, trigger_key FROM snippets WHERE id = ?", (sid,))
            exists = cursor.fetchone()
            # Legacy keywords stay editable; a new or changed keyword must expand unambiguously.
            if clean_trigger and not (exists and exists["trigger_key"] == clean_trigger):
                validate_trigger_shape(clean_trigger)
                cursor.execute(
                    "SELECT trigger_key FROM snippets WHERE trigger_key IS NOT NULL AND id != ?", (sid,)
                )
                for other in (row["trigger_key"] for row in cursor.fetchall()):
                    if other == clean_trigger:
                        raise TriggerError("duplicate", "Another snippet already uses this keyword")
                    if other.startswith(clean_trigger) or clean_trigger.startswith(other):
                        raise TriggerError("prefix", f"This keyword overlaps with {other}; keywords cannot start with each other")
            if exists:
                cursor.execute(
                    """
                    UPDATE snippets
                    SET title = ?, content = ?, folder_id = ?, trigger_key = ?, shortcut_number = ?, updated_at = ?
                    WHERE id = ?
                    """,
                    (title.strip() or "Untitled", content, folder_id, clean_trigger, shortcut, now, sid)
                )
            else:
                cursor.execute(
                    """
                    INSERT INTO snippets (
                        id, title, content, folder_id, trigger_key, shortcut_number, created_at, updated_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (sid, title.strip() or "Untitled", content, folder_id, clean_trigger, shortcut, now, now)
                )
            conn.commit()

        # Return refreshed snippet
        snippets = self.list_snippets()
        for snip in snippets:
            if snip["id"] == sid:
                return snip
        return {"id": sid, "title": title, "content": content, "folder_id": folder_id}

    def delete_snippet(self, snippet_id: str) -> bool:
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("DELETE FROM snippets WHERE id = ?", (snippet_id,))
            conn.commit()
            return cursor.rowcount > 0

    def export_snippets(self) -> Dict[str, Any]:
        """Export all snippet folders and snippets as a structured portable dictionary."""
        folders = self.list_folders()
        snippets = self.list_snippets()
        return {
            "version": "1.0",
            "exported_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "folders": folders,
            "snippets": snippets,
        }

    def import_snippets(self, payload: Dict[str, Any], merge: bool = True) -> Dict[str, int]:
        """Import snippet folders and snippets from a structured payload."""
        if not isinstance(payload, dict):
            raise ValueError("Import payload must be a JSON object")

        imported_folders = 0
        imported_snippets = 0

        with self._get_connection() as conn:
            cursor = conn.cursor()
            if not merge:
                cursor.execute("DELETE FROM snippets")
                cursor.execute("DELETE FROM snippet_folders WHERE id != 'default'")

            for folder in payload.get("folders", []):
                fid = folder.get("id") or str(uuid.uuid4())
                name = folder.get("name") or "Imported"
                icon = folder.get("icon") or "fa-folder"
                cursor.execute("SELECT id FROM snippet_folders WHERE id = ?", (fid,))
                if not cursor.fetchone():
                    cursor.execute(
                        "INSERT INTO snippet_folders (id, name, icon, created_at) VALUES (?, ?, ?, ?)",
                        (fid, name, icon, time.time())
                    )
                    imported_folders += 1

            for snip in payload.get("snippets", []):
                sid = snip.get("id") or str(uuid.uuid4())
                title = snip.get("title") or "Imported Snippet"
                content = snip.get("content") or ""
                fid = snip.get("folder_id") or "default"
                trig = snip.get("trigger_key")
                shortcut = snip.get("shortcut_number")

                cursor.execute("SELECT id FROM snippets WHERE id = ?", (sid,))
                if cursor.fetchone():
                    cursor.execute(
                        "UPDATE snippets SET title = ?, content = ?, folder_id = ?, trigger_key = ?, shortcut_number = ?, updated_at = ? WHERE id = ?",
                        (title, content, fid, trig, shortcut, time.time(), sid)
                    )
                else:
                    cursor.execute(
                        "INSERT INTO snippets (id, title, content, folder_id, trigger_key, shortcut_number, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                        (sid, title, content, fid, trig, shortcut, time.time(), time.time())
                    )
                    imported_snippets += 1
            conn.commit()

        return {"imported_folders": imported_folders, "imported_snippets": imported_snippets}


