VARIABLE_PATTERN = re.compile(r"\{\{([a-zA-Z0-9_:-]+)\}\}")


def parse_template_variables(template_str: str) -> List[Dict[str, str]]:
    """Inspect a snippet template and extract all dynamic variables."""
    matches = VARIABLE_PATTERN.findall(template_str)
    variables = []
    seen = set()
    for var in matches:
        if var in seen:
            continue
        seen.add(var)
        var_lower = var.lower()
        if var_lower.startswith("date") or var_lower.startswith("time") or var_lower in ("clipboard", "uuid"):
            var_type = "builtin"
        else:
            var_type = "prompt"
        variables.append({"name": var, "type": var_type})
    return variables


def render_template(
    template_str: str,
    values: Optional[Dict[str, str]] = None,
    current_clipboard: str = "",
) -> str:
    """Render a dynamic snippet template, expanding built-ins and custom prompt values."""
    user_values = values or {}
    now = datetime.datetime.now()

    def replacer(match: re.Match) -> str:
        var = match.group(1)
        var_lower = var.lower()

        # Custom user provided value overrides built-ins
        if var in user_values:
            return str(user_values[var])

        if var_lower == "date":
            return now.strftime("%Y-%m-%d")
        if var_lower.startswith("date:"):
            fmt = var[5:]
            try:
                return now.strftime(fmt)
            except Exception:
                return now.strftime("%Y-%m-%d")

        if var_lower == "time":
            return now.strftime("%H:%M:%S")
        if var_lower.startswith("time:"):
            fmt = var[5:]
            try:
                return now.strftime(fmt)
            except Exception:
                return now.strftime("%H:%M:%S")

        if var_lower == "clipboard":
            return current_clipboard
        if var_lower == "uuid":
            return str(uuid.uuid4())

        # Unfilled custom prompt remains placeholder or empty string
        return user_values.get(var, f"{{{{{var}}}}}")

    return VARIABLE_PATTERN.sub(replacer, template_str)


