import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadToolCatalog, SLICE_KEYS } from './tool-catalog.mjs';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const toolGuidePath = path.join(repositoryRoot, 'docs', 'TOOL-GUIDE.md');

// These two TOOL-GUIDE rows are generated from the live catalogue so parallel
// slices never hand-edit a shared count. Run after any catalogue change.
export function renderCountRows(catalogue) {
  const perSlice = SLICE_KEYS.map(slice => `${slice.replace('_', ' ')} ${catalogue.slices[slice]?.length ?? 0}`).join(', ');
  const pending = SLICE_KEYS.reduce((total, slice) => total + (catalogue.slices[slice]?.length ?? 0), 0);
  return [
    `| Search catalogue entries | **${catalogue.tools.length}** | Live merged \`TOOL_REGISTRY\` (core plus pending-tool slice modules); generated by \`node scripts/tool-counts.mjs\` |`,
    `| Pending-tool slice entries | **${pending}** | Development-only; ${perSlice}; generated by \`node scripts/tool-counts.mjs\` |`,
  ];
}

export function applyCountRows(guide, catalogue) {
  const [catalogueRow, pendingRow] = renderCountRows(catalogue);
  const lines = guide.split('\n');
  const catalogueIndex = lines.findIndex(line => line.startsWith('| Search catalogue entries |'));
  if (catalogueIndex === -1) throw new Error('TOOL-GUIDE.md is missing the "Search catalogue entries" row');
  lines[catalogueIndex] = catalogueRow;
  const pendingIndex = lines.findIndex(line => line.startsWith('| Pending-tool slice entries |'));
  if (pendingIndex === -1) lines.splice(catalogueIndex + 1, 0, pendingRow);
  else lines[pendingIndex] = pendingRow;
  return lines.join('\n');
}

export function main(argv = process.argv.slice(2), { catalogue = loadToolCatalog(), read = readFileSync, write = writeFileSync, log = console } = {}) {
  const guide = read(toolGuidePath, 'utf8');
  const updated = applyCountRows(guide, catalogue);
  if (argv.includes('--check')) {
    if (updated !== guide) {
      log.error('docs/TOOL-GUIDE.md tool counts are stale; run node scripts/tool-counts.mjs');
      return 1;
    }
    return 0;
  }
  if (updated !== guide) write(toolGuidePath, updated);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main();
}
